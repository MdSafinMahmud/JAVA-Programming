public class Literals {
    public static void main(String[] args) {
        byte age = 65;
        int age2 = 34;
        char ch = 'S';
        char ch2 = 'A';
        float f1 = 5.6f;
        double d1 = 4.66D;
        System.out.println(age);
        System.out.println(age2);
        System.out.println(ch);
        System.out.println(ch2);
        System.out.println(f1);
        System.out.println(d1);
    }
}
